"""Versioned evaluator definitions and score contracts shared by FP8/FP9."""

from __future__ import annotations

from copy import deepcopy
from typing import Any


def _definition(
    key: str,
    name: str,
    family: str,
    dimension: str,
    version: str,
    description: str,
    *,
    layer: str,
    question: str,
    comparison_target: str,
    calculation: str,
    scale: str,
    limitation: str,
    inputs: list[str],
    threshold: float | None = None,
    threshold_status: str = "none",
    implementation: str,
    framework: str = "project",
    model: str | None = None,
    is_local: bool = True,
    is_deterministic: bool = True,
    applicability: str = "all saved responses with required inputs",
) -> dict[str, Any]:
    configuration = {
        "layer": layer,
        "question": question,
        "comparison_target": comparison_target,
        "calculation": calculation,
        "scale": scale,
        "direction": "higher_is_better",
        "threshold": threshold,
        "threshold_status": threshold_status,
        "threshold_label": (
            f"Project review threshold {threshold:.2f}"
            if threshold is not None and threshold_status == "project_defined_unvalidated"
            else None
        ),
        "limitation": limitation,
        "inputs": inputs,
        "implementation": implementation,
        "framework": framework,
        "model": model,
        "applicability": applicability,
        "canonical_policy": "latest_attempt",
    }
    return {
        "key": key,
        "name": name,
        "family": family,
        "dimension": dimension,
        "version": version,
        "description": description,
        "configuration": configuration,
        "is_local": is_local,
        "is_deterministic": is_deterministic,
    }


