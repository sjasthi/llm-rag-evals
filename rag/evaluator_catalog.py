ALL_DEFINITIONS = BASELINE_DEFINITIONS + ADVANCED_DEFINITIONS
DEFINITIONS_BY_KEY = {definition["key"]: definition for definition in ALL_DEFINITIONS}


def definition_for(key: str) -> dict[str, Any]:
    """Return a defensive copy so callers cannot mutate the catalog."""
    if key not in DEFINITIONS_BY_KEY:
        raise KeyError(f"Unknown evaluator definition {key!r}")
    return deepcopy(DEFINITIONS_BY_KEY[key])
